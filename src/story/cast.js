// =============================================================================
// Maple Bay — CAST  (src/story/cast.js)
// Pure data. No engine imports. Everything here is plain objects/arrays.
//
// EXPORTS
//   DISTRICTS   string[]   the nine district ids used everywhere in src/story.
//   VENUES      { [venueId]: { name, district } }   canonical venue ids + sign names.
//   SPOTS       { [spotId]:  { district, desc } }   outdoor/non-venue places NPCs stand at.
//               Referenced from routines as 'spot:<spotId>'.
//   HOMES       { [homeId]:  { district, desc, enterable } }   NPC homes. 'player_building'
//               is whichever starter building the player picked (neighbors/super live there).
//   JOBS        { [jobId]:   { title, venue, boss } }   the 10 player jobs and who the boss is.
//   TRAITS      string[]   closed vocabulary for `personality` (dialogue.js verbs key off these).
//   TOPICS      string[]   closed vocabulary for likes/dislikes topics.
//   GIFTS       { [itemId]: { name, venue, price } }  giftable items; `venue` = where it is sold.
//   CAST        NPC[]      the named characters (see NPC shape below).
//   CAST_BY_ID  { [id]: NPC }  convenience lookup built from CAST.
//
// NPC SHAPE
//   id           string   unique, lowercase. Used by dialogue.js / story.js / texts.js.
//   name         string   full display name.
//   short        string   what the player calls them in bubbles and the phone contact list.
//   age          number
//   pronouns     'she/her' | 'he/him' | 'they/them'
//   group        'family' | 'friend' | 'staff' | 'neighbor' | 'regular'
//   role         string   one-phrase label shown under the name ("Diner owner").
//   district     district id where they are most often found.
//   home         home id from HOMES.
//   work         null | { venue: venueId | 'spot:<id>', job: string, bossOf?: jobId }
//                bossOf = the player job this NPC supervises (they send job texts in texts.js).
//   personality  [trait, trait, trait]  from TRAITS.
//   likes        { gifts: itemId[], topics: topic[] }   +bonus when gifted / talked about.
//   dislikes     { gifts: itemId[], topics: topic[] }   -penalty.
//   birthday     { season: 'spring'|'summer'|'autumn'|'winter', day: 1..14 }
//   flirtable    boolean  whether the (light, optional) flirt verb is ever offered.
//   routine      [{ days, from, to, place, anim }]
//                  days   array of 'mon'..'sun'
//                  from/to 'HH:MM' 24h. If to < from the block runs past midnight.
//                  place  venueId | 'home' | 'spot:<spotId>'
//                  anim   one of: stand walk sit eat drink phone talk wave type work lift dance read cheer
//                Any time not covered = at home, not available (asleep / indoors).
//                If two blocks overlap, the LATER entry in the list wins (general blocks
//                first, exceptions such as a lunch break after them).
//   look         string   free-text description for the character artist.
//   spec         suggested appearance: { skin, hair, hairColor, top, topColor, bottom,
//                bottomColor, hat, glasses, bag, age:'kid'|'adult'|'elder', outfit }
//   background   string   heritage / where they are from (Maple Bay is a modern, very diverse
//                American city). For writers and the character artist; not shown in game.
//   bio          string   one line for the contact card.
//   greetings    { low: string[], mid: string[], high: string[] }
//                low = stranger/acquaintance, mid = friend, high = close friend (or family).
//                Speech-bubble lines, <= 90 chars. {name} = player name.
// =============================================================================

