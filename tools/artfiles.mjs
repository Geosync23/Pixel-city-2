// Discovers art modules (src/art/**/*.js) and (re)generates src/art/index.js so nobody edits a shared index by hand.
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function artFiles() {
  const out = []; const walk = d => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (f.name.endsWith('.js') && f.name !== 'index.js' && f.name !== 'registry.js') out.push(p); } };
  walk(path.join(ROOT, 'src/art')); return out.sort();
}
export function genIndex() {
  const files = artFiles().map(f => './' + path.relative(path.join(ROOT, 'src/art'), f).split(path.sep).join('/'));
  const src = '// GENERATED by tools/artfiles.mjs - do not edit.\nimport { reg } from \'./registry.js\';\n' + files.map((f, i) => `import * as m${i} from '${f}';`).join('\n') + '\n' + files.map((f, i) => `reg(m${i}, '${f}');`).join('\n') + '\n';
  const p = path.join(ROOT, 'src/art/index.js'); if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== src) fs.writeFileSync(p, src);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) genIndex();
